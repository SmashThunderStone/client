import { createRequire } from 'node:module';
import { readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

// esbuild is already in the pnpm store for Vite. Resolve it there so this
// script does not add another dependency.
const pnpmDir = fileURLToPath(new URL('../node_modules/.pnpm', import.meta.url));
const esbuildDir = readdirSync(pnpmDir)
  .filter((name) => name.startsWith('esbuild@'))
  .sort()
  .at(-1);
if (!esbuildDir) {
  throw new Error('esbuild is not installed');
}
const require = createRequire(
  join(pnpmDir, esbuildDir, 'node_modules/esbuild/package.json'),
);
const { build } = require('esbuild');

await build({
  absWorkingDir: fileURLToPath(new URL('..', import.meta.url)),
  entryPoints: ['scripts/media-function/handler.ts'],
  outfile: 'api/media.js',
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  legalComments: 'none',
  banner: {
    js: [
      '// Generated by scripts/bundle-media-function.mjs.',
      '// CommonJS bundle of the SmashCast media upload function.',
      '// Edit scripts/media-function/handler.ts, then rerun that script.',
    ].join('\n'),
  },
  footer: {
    js: [
      'const __smashcastMediaHandler = module.exports.default;',
      'const __smashcastMediaConfig = module.exports.config;',
      'module.exports = __smashcastMediaHandler;',
      'module.exports.default = __smashcastMediaHandler;',
      'module.exports.config = __smashcastMediaConfig;',
    ].join('\n'),
  },
});
